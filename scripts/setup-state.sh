#!/usr/bin/env bash
#
# Zairakai NPM Dev Tools - Setup State
# What the setup publishes in a project, compared with what the project has. Shared by setup-check.sh, setup-update.sh and
# uninstall-package.sh. This file is sourced after config.sh, it runs nothing.
#
# The files are generated in a temporary folder with the publication of setup-project.sh itself, then compared with the
# project's. Nothing is written in the project here. A file that differs can be a change of the project or a file late on
# the package: the check cannot tell, it shows the difference.
#

SETUP_BACKUP_FOLDER=".dev-tools-backup"

# The groups of the default publication. The hooks are a git setting, the CI file and the governance files are made the
# project's own when it publishes them, and tsconfig.json is the project's own (it extends the base and adds its paths).
SETUP_GROUPS=(quality style testing)

# The files of the root that the publication reads to choose its files: a bridge is not created when the project has its
# own configuration of the tool.
SETUP_INPUTS=(
  package.json composer.json artisan
  eslint.config.{js,mjs,cjs,ts,mts,cts}
  prettier.config.{js,mjs,cjs,ts} .prettierrc{,.json,.yaml,.yml,.js,.mjs,.cjs}
  stylelint.config.{js,mjs,cjs} .stylelintrc{,.json,.yaml,.yml,.js,.mjs,.cjs}
  vitest.config.{js,mjs,cjs,ts} vitest.workspace.{js,ts} vite.config.{js,mjs,cjs,ts}
)

# The files of the project that the generation copied, so they are not part of the setup
SETUP_MIRRORED=()

# Helpers
# ================

# A Laravel app with laravel-dev-tools: it owns the Makefile and the .editorconfig (the full-stack ones), so the JS setup
# does not check them
setup_is_fullstack() {
  [[ "$PROJECT_TYPE" == "laravel-app" ]] \
    && [[ -f "${PROJECT_ROOT}/vendor/zairakai/laravel-dev-tools/scripts/setup-package.sh" ]]
}

# Whether the Makefile of the project includes the dev-tools (generated by the setup, or injected into an existing one)
setup_makefile_includes() {
  grep -qE 'js-dev-tools|DEV_TOOLS_NPM' "$1" 2> /dev/null
}

# What differs between the file of the project and the file of the package, in a few words: the keys of a JSON file, or
# the number of lines of another file
setup_difference() {
  local mine="$1" generated="$2" file="$3" detail=""

  if [[ "$file" == *.json ]] && command_exists node; then
    detail="$(node -e '
      const fs = require("fs")
      const flat = (value, path, out) => {
        if (value && typeof value === "object" && !Array.isArray(value)) {
          for (const key of Object.keys(value)) flat(value[key], path ? path + "." + key : key, out)
        } else out[path] = JSON.stringify(value)
        return out
      }
      let mine, theirs
      try {
        mine = flat(JSON.parse(fs.readFileSync(process.argv[1], "utf8")), "", {})
        theirs = flat(JSON.parse(fs.readFileSync(process.argv[2], "utf8")), "", {})
      } catch { process.exit(3) }
      const only = (a, b) => Object.keys(a).filter((key) => !(key in b))
      const changed = Object.keys(mine).filter((key) => key in theirs && mine[key] !== theirs[key])
      const list = (label, keys) => (keys.length ? label + ": " + keys.join(", ") : "")
      console.log([
        list("only in the project", only(mine, theirs)),
        list("only in the package", only(theirs, mine)),
        list("changed", changed),
      ].filter(Boolean).join("; "))
    ' "$mine" "$generated" 2> /dev/null || true)"
  fi

  if [[ -z "$detail" ]]; then
    local in_project in_package
    in_project="$(grep -cvxFf "$generated" "$mine" || true)"
    in_package="$(grep -cvxFf "$mine" "$generated" || true)"
    detail="${in_project} line(s) only in the project, ${in_package} line(s) only in the package"
  fi

  echo "$detail"
}

# Copies a file of the project in .dev-tools-backup/<UTC date>/, under its path from the root (the folder of backup_file).
# The folder ignores itself for git: the copies are never committed by mistake.
setup_backup() {
  backup_file "$1" || return 0

  local base="${BACKUP_DIR%/*}"
  [[ -f "${base}/.gitignore" ]] || printf '*\n' > "${base}/.gitignore"
}

# Generation
# ================

# Generates in the folder $1 the files that the setup would publish in this project
setup_generate() {
  local temporary="$1" name key group publisher
  local -a first=(--with-makefile) kept=()

  mkdir -p "${temporary}/node_modules/@zairakai"
  ln -s "$DEV_TOOLS_ROOT" "${temporary}/node_modules/@zairakai/js-dev-tools"
  publisher="${temporary}/node_modules/@zairakai/js-dev-tools/scripts/setup-project.sh"

  # What the publication reads in the project to choose its files: the type of the project and its configurations
  SETUP_MIRRORED=()
  for name in "${SETUP_INPUTS[@]}"; do
    if [[ -f "${PROJECT_ROOT}/${name}" ]]; then
      cp "${PROJECT_ROOT}/${name}" "${temporary}/${name}"
      SETUP_MIRRORED+=("$name")
    fi
  done

  # A bridge that the setup made is part of the setup: it is generated again, not read as the project's own configuration
  for key in eslint prettier stylelint vitest; do
    name="${key}.config.mjs"
    if [[ -f "${temporary}/${name}" ]] && grep -qF "config/dev-tools/${key}.config.js" "${temporary}/${name}"; then
      rm -f "${temporary}/${name}"
    fi
  done
  for name in "${SETUP_MIRRORED[@]}"; do
    [[ -f "${temporary}/${name}" ]] && kept+=("$name")
  done
  SETUP_MIRRORED=("${kept[@]}")

  setup_is_fullstack && first=()

  for group in "${SETUP_GROUPS[@]}"; do
    (cd "$temporary" && bash "$publisher" "--publish=${group}" --force --silent "${first[@]}") > /dev/null 2>&1 || true
    first=()
  done

  if ! setup_is_fullstack; then
    cp "${DEV_TOOLS_ROOT}/.editorconfig" "${temporary}/.editorconfig"
  fi
}

# The files that the generation wrote, from the root of the project, in order
setup_generated_files() {
  local temporary="$1" file name skip

  while IFS= read -r file; do
    skip=false
    for name in "${SETUP_MIRRORED[@]}"; do
      [[ "$file" == "$name" ]] && skip=true
    done
    [[ "$skip" == "true" ]] || echo "$file"
  done < <(cd "$temporary" && find . -type f ! -path './node_modules/*' ! -path "./${SETUP_BACKUP_FOLDER}/*" | sed 's|^\./||' | sort)
}

# One line per file of the setup: "<state>|<file>|<detail>", the state being same, missing or different
setup_results() {
  local temporary="$1" file mine generated state detail

  while IFS= read -r file; do
    mine="${PROJECT_ROOT}/${file}"
    generated="${temporary}/${file}"
    state="same"
    detail=""

    if [[ "$file" == "Makefile" ]]; then
      # A project adds its own targets: its Makefile is right when it includes the dev-tools
      setup_makefile_includes "$mine" || state="missing"
    elif [[ ! -f "$mine" ]]; then
      state="missing"
    elif ! cmp -s "$mine" "$generated"; then
      state="different"
      detail="$(setup_difference "$mine" "$generated" "$file")"
    fi

    printf '%s|%s|%s\n' "$state" "$file" "$detail"
  done < <(setup_generated_files "$temporary")
}
